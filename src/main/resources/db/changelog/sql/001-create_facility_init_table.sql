    CREATED_BY VARCHAR(512) NOT NULL,
    OPENED_IN TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    UPDATED_BY VARCHAR(512) NOT NULL
);