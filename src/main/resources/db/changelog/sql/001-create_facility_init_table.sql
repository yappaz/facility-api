    STREET VARCHAR(512) NOT NULL,
    STREET_NUMBER VARCHAR(64) NOT NULL,
    POST_CODE VARCHAR(256) NOT NULL,
    LATITUDE DECIMAl NOT NULL,
    LONGITUDE DECIMAL NOT NULL,
    TYPE VARCHAR(256) NOT NULL,
    STATUS VARCHAR(256) NOT NULL,
